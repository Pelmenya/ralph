// Снятие комментариев с исходного текста — общая деталь барьеров, сканирующих КОД.
// Живёт отдельным модулем, потому что сканов стало два: `core-purity` ищет проектные
// значения и команды форжа, `seam-defaults` — тихие GitHub-дефолты швов. Копия стриппера
// в каждом означала бы, что дыру в границе «код vs комментарий» надо чинить дважды, —
// а первый же круг ревью показал, насколько эта граница неочевидна (см. историю ниже).

// Вырезание блочных комментариев /* … */ ПОСИМВОЛЬНО, с учётом строковых литералов
// (#367-ревью). Наивный regex `/\/\*[\s\S]*?\*\//` не знает про строки: глоб-строка в коде
// ('src/**/*.ts' содержит и `/*`, и `*/`) заставила бы его вырезать кусок строки, а при
// двух таких литералах на разных строках — ВСЁ между ними, включая реальную специфику, и
// тест бы промолчал (латентный false-negative барьера). Сканер идёт по символам: внутри
// строкового литерала ('…' / "…" / `…`) маркеры комментариев НЕ маркеры (копируем как есть,
// так специфика в СТРОКЕ кода по-прежнему ловится); блочный /* … */ вне строк вырезаем
// целиком (в т.ч. многострочный); строчный // … оставляем нетронутым (его уберёт построчный
// фильтр ниже, если строка — комментарий целиком). Хвостовые `// …` — по опции
// `dropTrailing`, у двух сканов она разная (почему — в TStripOptions). Регэкспы
// литералов сканер не парсит — за рамками ревью и не хуже прежнего regex-подхода.
export type TStripOptions = {
    /**
     * Резать ли ХВОСТОВОЙ `// …` (комментарий после кода на той же строке).
     *
     * Полярность здесь противоположна у двух сканов, и это не вкусовщина.
     * `core-purity` ищет проектную строку и хвостовые оставляет: наивный срез по первому
     * `//` съел бы `//` внутри URL-строки и пропустил бы настоящую специфику — там
     * false-negative дороже редкого false-positive на стиле «код; // acme-shop».
     * `seam-defaults` спрашивает обратное — «ведёт ли ЭТО ВЫРАЖЕНИЕ к шву», — и там
     * хвостовой комментарий читается как часть выражения: пометка `// adapters.taskSource`
     * рядом с локальным вызовом делает барьер слепым (показано мутацией на ревью !4).
     * Резать безопасно ровно потому, что сканер посимвольный и про литералы знает: `//`
     * внутри строки маркером не считается.
     */
    dropTrailing?: boolean;
    /**
     * Вычищать ли СОДЕРЖИМОЕ строковых литералов (кавычки остаются, переводы строк
     * внутри шаблонных строк сохраняются — нумерация строк обязана сходиться с файлом).
     *
     * Нужна сканам, которые ищут КОНСТРУКЦИИ кода (присваивание переменной, вызов),
     * а не проектные значения: текст подсказок в ядре содержит фрагменты вроде
     * `adapters.coderRuntime='kimi'` — это проза об опции конфига, и без вычистки барьер
     * на запись в поле `adapters` краснел бы на исправном файле (ревью !5). Сканы
     * ЗНАЧЕНИЙ (`core-purity` ищет проектные строки) обязаны оставить опцию выключенной:
     * для них строка — тоже код. Цена включения: код внутри `${…}` шаблонной строки
     * сканер считает содержимым литерала и вычищает — эту щель закрывает не текст,
     * а механизм (Object.freeze набора адаптеров).
     */
    blankStrings?: boolean;
};

export function stripBlockComments(
    src: string,
    { dropTrailing = false, blankStrings = false }: TStripOptions = {},
): string {
    let out = '';
    let i = 0;
    const n = src.length;
    while (i < n) {
        const c = src[i];
        const c2 = src[i + 1];
        // Строковый литерал — копируем целиком, экранирование учитываем, маркеры внутри
        // комментариями не считаем.
        if (c === "'" || c === '"' || c === '`') {
            out += c;
            i++;
            while (i < n) {
                if (src[i] === '\\') {
                    if (!blankStrings) out += src[i] + (src[i + 1] ?? '');
                    i += 2;
                    continue;
                }
                if (src[i] === c) {
                    out += c;
                    i++;
                    break;
                }
                // При blankStrings содержимое выбрасывается, но '\n' остаётся: номер
                // строки в тексте находки обязан сходиться с файлом (как у блочных
                // комментариев выше).
                if (!blankStrings || src[i] === '\n') out += src[i];
                i++;
            }
            continue;
        }
        // Строчный комментарий // … — вне строкового литерала, значит настоящий.
        // При dropTrailing выбрасываем его текст (перевод строки остаётся — нумерация
        // строк обязана сходиться с файлом); иначе копируем как есть, и строки-целиком-
        // комментарии уберёт построчный фильтр ниже.
        if (c === '/' && c2 === '/') {
            while (i < n && src[i] !== '\n') {
                if (!dropTrailing) out += src[i];
                i++;
            }
            continue;
        }
        // Блочный комментарий /* … */ — вырезаем целиком (в т.ч. многострочный), но
        // ПЕРЕВОДЫ СТРОК внутри сохраняем. Иначе номера строк в тексте находки перестают
        // сходиться с файлом, и барьер отправляет читателя не туда: сообщение «строка 2139»
        // на файле, где нарушение в 3510-й, дороже отсутствия номера вовсе.
        if (c === '/' && c2 === '*') {
            i += 2;
            while (i < n && !(src[i] === '*' && src[i + 1] === '/')) {
                if (src[i] === '\n') out += '\n';
                i++;
            }
            i += 2; // пропускаем закрывающие */
            continue;
        }
        out += c;
        i++;
    }
    return out;
}

// Убираем комментарии, чтобы отличить проектную строку в КОДЕ (нарушение переносимости)
// от поясняющего комментария-примера («был 'AcmeCorp'/1» — это норма и часть истории).
// Блочные /* … */ вырезает stripBlockComments (с учётом строк), затем выкидываем строки-
// целиком-комментарии (`^\s*//`, `^\s*\*` — продолжение блочного, `^\s*/\*`) — заменяя
// их ПУСТЫМИ строками, а не выбрасывая: номер строки в находке обязан сходиться с файлом.
export function stripComments(src: string, opts: TStripOptions = {}): string {
    return stripBlockComments(src, opts)
        .split('\n')
        .map((line) => (/^\s*(\/\/|\*|\/\*)/.test(line) ? '' : line))
        .join('\n');
}
