// Задача 11: хореография ветки ушла из промпта кодер-сессии в раннер.
//
// Барьер, а не абзац в правилах (инвариант №5): промпт правят чаще кода, и «верни пару
// строк про git checkout» — самая естественная правка на свете. Она же возвращает дефект,
// ради которого всё делалось: сессия слабой модели, перебирающая идиомы переключения,
// коммитила на detached HEAD, и коммит оставался недостижим ни из одной ветки.
//
// Сканируется ТЕКСТ промпта, а не поведение модели: поведение мы не контролируем, а вот
// что мы ей велим — контролируем целиком.
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const CANON_ROOT = resolve(import.meta.dirname, '..');
const PROMPT = readFileSync(resolve(CANON_ROOT, 'ralph.md'), 'utf8');

/**
 * Слова, которыми ветку переключают или заводят. Ищем ИМЕННО СЛОВО, а не `git <слово>`:
 * привязка к `git` рядом обходится любой обычной формой — `git -C . switch`,
 * `git -c key=value checkout` (ревью, 1-й проход), — и барьер, который обходится
 * штатным синтаксисом, не барьер.
 *
 * Ложные срабатывания здесь безвредны: в промпте кодер-сессии этим словам взяться неоткуда,
 * а `git branch` не запрещаем — им спасают работу, и в тексте про спасение он законен.
 */
const SWITCH_WORDS = [/\bcheckout\b/i, /\bswitch\b/i, /\bworktree\s+add\b/i];

describe('промпт кодер-сессии (ralph.md)', () => {
    it('не велит сессии переключать ветку — это работа раннера', () => {
        const found = SWITCH_WORDS.filter((re) => re.test(PROMPT)).map(String);

        expect(found).toEqual([]);
    });

    it('барьер не привязан к форме записи команды', () => {
        // Проба от противного: обходные формы, которыми прежний скан не краснел.
        for (const bypass of ['git -C . switch feature/x', 'git -c a=b checkout -b feature/x']) {
            expect(SWITCH_WORDS.some((re) => re.test(bypass))).toBe(true);
        }
    });

    it('не велит сессии создавать ветку фазы', () => {
        // `-b` у checkout и `--create` у switch — обе формы заведения ветки сессией.
        expect(PROMPT).not.toMatch(/checkout\s+-b|switch\s+(-c|--create)/);
    });

    it('говорит прямо, что ветку поставил раннер: молчание читается как «разберись сам»', () => {
        expect(PROMPT).toMatch(/ветку тебе уже поставил раннер/i);
    });

    it('запрещает уход с ветки явно, а не по умолчанию', () => {
        expect(PROMPT).toMatch(/ветку не переключай/i);
    });
});
