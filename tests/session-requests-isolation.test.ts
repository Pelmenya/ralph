// #144: прогон тестов ядра не должен зависеть от ЖИВОГО файла намерений в дереве.
//
// Симптом, ради которого файл заведён: стоит сессии оставить хоть одно намерение —
// и `npm run test` краснеет на сценарных тестах гейта (`hold`/`blocked`), которые к
// каналу намерений отношения не имеют вовсе. Диагноз при этом уводит в сторону: падает
// «hold остаётся нетронутым», а причина — файл на диске рядом.
//
// Механика утечки: `applySessionRequests` по умолчанию читает РЕАЛЬНЫЙ путь
// `.claude/ralph/ralph.requests.jsonl`, и тест, забывший подменить `applySessionRequestsFn`,
// подхватывал намерения живого прогона, применял их через боевой шов форжа (то есть уходил
// в настоящий `gh` и висел до таймаута), а сдача вставала fail-closed — с другим числом
// сессий и вызовов, чем ждал ассерт.
//
// Цена дефекта — не в неудобстве: гейт мерджа гоняет тесты в ДЕРЕВЕ РАННЕРА и ровно в тот
// момент, ради которого канал заведён (сессия отработала, намерения оставлены), — то есть
// петля не сдавала фазу при исправном коде.
//
// ── Почему здесь НЕТ фикстуры на боевом пути (#72-ревью) ──────────────────────────
// Первая редакция этого файла писала шесть настоящих на вид намерений по РЕАЛЬНОМУ пути
// в дереве раннера (с бэкапом живого файла рядом) — то есть заводила ровно ту связь
// прогона с живым деревом, которую сама же и закрывает. Цена: между `beforeAll` и
// `afterAll` живёт окно, в котором по боевому пути лежит готовый батч; прогон убит
// (таймаут гейта, OOM, рестарт петли, Ctrl-C) — `afterAll` не отработал, файл остался, и
// раннер после сессии применяет его: комментарий, закрытие, `blocked` и заведение карточки.
// Мутации трекера из тестовой фикстуры — цена, которой этот тест не стоит.
//
// Доказательства при этом не терялось: `makeRunLoopScenario` подставляет
// `noSessionRequests`, так что сценарный прогон не читает файл ПО ПОСТРОЕНИЮ, а не потому
// что файла нет, — и «файл на диске не влияет» тот describe проверял вхолостую. Инвариант
// целиком держит проверка ниже: боевой `readSessionRequests` под RALPH_NO_SIDE_EFFECTS
// бьёт по рукам, а не читает тихо. Значит следующий тест, забывший заглушку, упадёт СРАЗУ
// и с внятной причиной, а не через полгода и не в зависимости от того, что лежит на диске.
import { describe, it, expect } from 'vitest';
// @ts-expect-error — JS-entry раннера без деклараций типов (тот же приём, что в
// orchestrator.test.ts, #366): дефолт ralph.js — ре-экспорт runtime фабрики.
import ralph from '../ralph.js';
import { makeRunLoopScenario as scenario, noSessionRequests } from './test-helpers.ts';

describe('боевое чтение файла намерений в тестах — под предохранителем', () => {
    it('applySessionRequests без подменённого readFn бьёт по рукам, а не читает диск', () => {
        expect(() =>
            ralph.applySessionRequests({
                cfg: { issueLabels: [] },
                dry: true,
                writeFn: () => {},
                removeFn: () => {},
                logFn: () => {},
                pushEventFn: () => {},
            }),
        ).toThrow(/readSessionRequests/);
        // Журнал сверяет общий afterEach (test-setup.ts) — попытка здесь ожидаема, поэтому
        // вычерпываем её сами, иначе тест покраснел бы на собственном доказательстве.
        expect(ralph.sideEffectAttempts.splice(0).join(' ')).toMatch(/readSessionRequests/);
    });

    it('сценарный прогон канал намерений не открывает вовсе — заглушка стоит в обвязке', () => {
        // Второй конец того же инварианта, и без единой записи на диск: сценарий гейта
        // проходит круг разбора blocked, ни разу не дойдя до боевого дефолта, — а дойди
        // он туда, guard выше уронил бы прогон с внятной причиной. Заодно фиксируется,
        // что заглушка отдаёт ВЕСЬ контракт канала (пять полей), а не пару `applied/failed`:
        // ядро сегодня терпит узкую форму (`res.prFindings ?? []`), и две заглушки одного
        // канала с разной формой — тот самый разъезд, ради которого хелпер и заводился.
        const s = scenario();
        s.pass('blocked');
        expect(s.state.blockedHeals).toBe(1);
        expect(s.runClaudeFn).toHaveBeenCalledTimes(2);
        expect(Object.keys(noSessionRequests()).sort()).toEqual([
            'applied',
            'closedIssues',
            'failed',
            'prBlocked',
            'prFindings',
        ]);
    });
});
