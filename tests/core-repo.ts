// Где лежит ядро: корень своего репозитория (клон канона, его CI) или копия внутри дерева
// потребителя (`.claude/ralph` до внешней установки, задача 74).
//
// Часть барьеров проверяет не код ядра, а РЕПОЗИТОРИЙ канона: историю коммитов, ссылки
// корневых доков на `.claude/` и `LICENSE`, guard и настройки хуков из `.claude/`. В копию
// у потребителя эти файлы не едут — синхронизация по manifest берёт только код, — и там
// такие барьеры краснели бы на том, чего в копии нет по построению. Ту же ревизию они уже
// прошли в гейте канона, поэтому у потребителя они пропускаются `skipIf`, видимо в отчёте,
// а не тихим `return`.
import { spawnSync } from 'node:child_process';
import { resolve } from 'node:path';

// От каталога модуля, а не от cwd: ядро гоняется и из своего корня, и из дерева потребителя.
export const CORE_ROOT = resolve(import.meta.dirname, '..');

/**
 * Ядро — корень git-репозитория, то есть это сам канон, а не его копия у потребителя.
 * Отказ git — исключение, а не «копия»: предикат решает, пропустить ли барьеры, и
 * сломанный `git` (нет бинаря, `safe.directory`) иначе молча гасил бы их в самом каноне.
 */
export function coreIsRepoRoot(): boolean {
    const top = spawnSync('git', ['-C', CORE_ROOT, 'rev-parse', '--show-toplevel'], {
        encoding: 'utf-8',
    });
    if (top.status !== 0) {
        throw new Error(
            `git rev-parse в ${CORE_ROOT} не ответил — раскладку ядра не определить: ` +
                (top.stderr || String(top.error)),
        );
    }
    return top.stdout.trim() === CORE_ROOT;
}
