// Подопытный для барьера «смерть процесса-владельца уносит песочницу» (канон, задача 26).
//
// Отдельный процесс, а не сам тест: проверяемый путь — гибель ВЛАДЕЛЬЦА живого прогона,
// и убивать ради него worker vitest значило бы убивать сьют вместе с проверкой. Помощник
// поднимает зависший прогон (кодер-сессия не возвращается) и печатает корень песочницы,
// чтобы тест знал, за чем наблюдать; дальше он висит в `spawnSync`, пока его не убьют.
import { buildLiveSandbox, runLiveCycle } from '../live-sandbox.ts';

const sb = buildLiveSandbox({ coderScript: 'sleep 600' });
// Строка обязана уйти немедленно и целиком: тест ждёт именно её, а буфер stdout при
// убийстве -9 не сбрасывается.
process.stdout.write(`SANDBOX ${sb.root}\n`);
// Срок заведомо больше того, что отведено тесту: помощник не должен успеть закончить сам —
// иначе проверка «его убили, и всё умерло» доказывала бы штатный выход.
runLiveCycle(sb, 600_000);
