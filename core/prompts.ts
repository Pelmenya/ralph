// ДАННЫЕ ФОРЖА В ПРОМПТЕ (#50). Сессия не может прочитать ни карточку, ни комментарии PR:
// у неё нет ни CLI форжа, ни HTTP-доступа. Читает петля, а сюда приносит готовый текст — и
// он ОБЯЗАН быть обёрнут как ДАННЫЕ, НЕ ИНСТРУКЦИИ (C3): тело чужой карточки и комментарии
// публичного репозитория — ровно тот канал, по которому в сессию приезжает инъекция.
// Обёртку делает `wrapAsData`, а не вызывающий: забыть её в одном месте из трёх — вопрос
// времени.
// Делимитеры данных: текст между ними сессия обязана считать содержимым, а не приказом.
// Маркер длинный и однозначный намеренно — короткий вроде ``` встречается внутри самих
// данных, и тогда граница теряется ровно там, где она важнее всего.
// Ось серьёзности заводится в одном месте — `review-of-fixes.ts`, — и союз литералов
// не даёт вписать в промпт уровень, которого у петли нет.
