export type GateHealPromptParams = {
    branch: string;
    checkName: string;
    checkCmd: string;
    excerpt: string;
    gateCmdList: string;
    // #269: отказ пойман НЕ локальным гейтом, а чеком PR у форжа. Флаг, а не готовый
    // текст: подсказку собирает эта функция (все тексты сессий живут здесь), а цикл
    // сообщает только факт.
    forgeOnly?: boolean;
    // #269-ревью: ПРОЕКТНАЯ половина подсказки — где именно расходятся среды хоста
    // и контейнера ЭТОГО контура (пути, uid, лимиты, имена переменных окружения).
    // Приходит из конфига (`forgeEnvHint`), а не живёт константой здесь: перечень —
    // свойство одного форжа и одной обёртки гейта, и в переносимом ядре он превращался бы
    // в ложный след на любом другом. Не задан ⇒ остаётся только нейтральная половина.
    forgeEnvHint?: string;
};

// #269: подсказка для случая, когда локальный гейт зелёный, а чек форжа красный. Это не
// украшение промпта, а единственное, что отличает такую сессию от обычной чини-сессии:
// «воспроизведи чек локально» здесь заведомо не сработает, и без указания искать разницу
// СРЕД модель полчаса гоняет зелёный набор и объявляет отказ невоспроизводимым.
//
// Текст НАМЕРЕНИЕ, а не перечень мест: конкретика («рабочий каталог `/repo`», имена
// переменных окружения площадки) уехала в конфиг проекта параметром `forgeEnvHint` —
// правка по ревью #269. В ядре она нарушала инвариант #45, а барьер `core-purity` её
// пропускал из-за `\b` перед подчёркиванием — то есть строка прошла не потому, что была
// законна, а потому, что барьер был слеп к этой форме (барьер тоже расширен).
const FORGE_ONLY_HINT =
    'ВАЖНО: локальный набор на этой же голове ЗЕЛЁНЫЙ — отказ живёт только в контейнере ' +
    'форжа, и «воспроизвести локально» его не выйдет: ищи разницу СРЕД, а не дефект, ' +
    'который виден на хосте. ';

// Самолечение гейта: чек упал на точном sha PR-головы, чинит причину отдельная сессия.
export function buildGateHealPrompt({
    branch,
    checkName,
    checkCmd,
    excerpt,
    gateCmdList,
    forgeOnly = false,
    forgeEnvHint,
}: GateHealPromptParams): string {
    // #269-ревью: при `forgeOnly` в `checkCmd` лежит АДРЕС упавшего куба («куб «test»
    // прогона 356»), а не то, что можно выполнить, — и префикс «команда:» делал промпт
    // ложным. Рядом в том же тексте перечислен `gateCmdList` из настоящих команд, и
    // смешение двух смыслов в одном поле путало сессию сильнее, чем помогало.
    const where = forgeOnly ? `(${checkCmd})` : `(команда: ${checkCmd})`;
    // #269-ревью: вторая половина фразы ОТМЕНЯЛА подсказку строкой выше — «воспроизвести
    // локально не выйдет» и тут же «воспроизведи чек локально». Из двух указаний модель
    // берёт последнее, то есть ровно то, от которого её отговаривают.
    const how = forgeOnly
        ? `Дерево уже стоит на ветке ${branch} — найди и исправь ПРИЧИНУ чтением кода ` +
          'и сравнением сред; локальный прогон здесь ничего не покажет.'
        : `Дерево уже стоит на ветке ${branch} — воспроизведи чек локально, ` +
          'найди и исправь ПРИЧИНУ.';
    const hint = forgeOnly
        ? `${FORGE_ONLY_HINT}${forgeEnvHint ? `${forgeEnvHint.trim()} ` : ''}`
        : '';
    return (
        `Гейт мерджа фазы упал на чеке ${checkName} ${where} в ветке ${branch}. ` +
        `Хвост вывода ошибки: ${excerpt}. ${hint}${how} Затем добейся зелёного всего набора: ${gateCmdList}. ${COMMIT_RULE} Закоммить ` +
        `исправление в ${branch}. ${PUSH_RULE} ${intentsRule()} Если причина не чинится кодом ` +
        `автономно — запиши намерение pr-block с объяснением. ${HOLD_RULE}`
    );
}

// #110: обещание про карточки собирается из ДЕЙСТВУЮЩЕГО порога `review.backlogSeverityFloor`,
// а не выписано константой. Пока фраза была фиксированной, промпт обещал карточку за каждый
// ⚪ nit, а фильтр порога заводить её отказывался — сессия тратила ходы на находки, которые
// петля молча отбрасывала, а человек искал карточки, которых нет. Это тот же класс, что
// враньё в строке лога: сообщения ядра обязаны быть правдой (`core-purity.test.ts`).
//
// Порог сюда приходит параметром, а не читается из конфига: функции модуля чистые, и
// подстановка значения — единственный способ, при котором текст не разъедется с ключом
// при смене значения.
function backlogPromise(severityFloor: FixSeverity | undefined): string {
    if (!severityFloor) {
        return 'minor и nit петля заведёт карточками и мердж задерживать не будет';
    }
    return (
        `находки не мельче уровня «${severityFloor}» петля заведёт карточками и мердж ` +
        'задерживать не будет, а всё, что мельче, останется комментарием на PR — карточкой ' +
        'оно не станет'
    );
}

