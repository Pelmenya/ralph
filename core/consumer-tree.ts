/**
 * Кто держит дерево потребителя актуальным (канон, задача 28).
 *
 * Задача 23 заякорила пути скриптов потребителя к `consumerRoot`: инструмент берётся из
 * дерева ПОТРЕБИТЕЛЯ, а не из ветки фазы, — иначе петля исполняла бы версию скрипта,
 * написанную той самой сессией, работу которой она надзирает. Якорь остаётся; вопрос,
 * который он открыл, — другой: **это дерево раннер не обновлял вовсе**. Скрипт, добавленный
 * фазовым PR, там не появлялся, вызов оставался fail-open, и «работает ли синк доски»
 * зависело от того, когда человек последний раз делал `pull` руками.
 *
 * Контракт: **обновляет раннер, сразу после мерджа фазы, best-effort и только вперёд**.
 * Отвергнуты два соседних варианта:
 *
 *   - «брать артефакты из дерева работы» — снимает якорь задачи 23 вместе с его смыслом:
 *     сессия, правящая свой же инструмент, получила бы его неотревьюенную версию в том же
 *     прогоне. Стабильность инструмента — свойство управляемости, а не удобства;
 *   - «обновление — работа потребителя» — честно, но враждебно AFK: раннер и заводился
 *     ради прогонов без человека, а такой контракт требует человека МЕЖДУ фазами, то есть
 *     ровно в том окне, ради которого он работает.
 *
 * Момент выбран не «когда угодно, лишь бы почаще»: обновление идёт МЕЖДУ фазами. Внутри
 * фазы версия инструмента обязана стоять на месте (та же задача 23), а после мерджа
 * актуальная версия — ровно та, что только что прошла ревью и гейт.
 *
 * Дерево потребителя — дерево ЧЕЛОВЕКА, и это задаёт все ограничения ниже: не трогаем
 * грязное, не трогаем чужую ветку, не сливаем ничего, кроме fast-forward, и никогда не
 * разрешаем конфликтов за него. Каждый отказ называется в логе вместе с командой, которой
 * человек закончит сам, — «не смог» без адреса неотличимо от «не понадобилось».
 *
 * Чего эта функция НЕ делает, и это решение, а не упущение:
 *
 *   - **не рекурсирует в подмодули.** Каталог продукта у потребителя — подмодуль внутри
 *     `consumerRoot`; `--recurse-submodules` подменил бы код продукта под работающей
 *     петлёй. Ревизия продукта меняется lifecycle-операцией launcher'а (`./ralph update`),
 *     где у неё есть транзакция и рестарт, а не побочкой обновления соседнего дерева;
 *   - **не перечитывает `ralph.config.json`.** Петля исполняет конфиг, загруженный при
 *     старте; приехавшая правка конфига вступит в силу с рестартом. Это отдельная задача
 *     («фикс ядра не действует до перезапуска»), и делать вид, что обновление файла на
 *     диске её решает, было бы хуже молчания.
 *
 * TS-модуль без билд-шага: исполняется нативным type stripping Node 24 (erasable-only).
 */
import type { TResolvedRoots } from './roots.ts';

/** Чем кончилось обновление. Решение вызывающего по каждому исходу — только лог. */
export type TConsumerTreeKind =
    'no-roots' | 'same-tree' | 'dirty' | 'off-main' | 'failed' | 'updated';

export type TConsumerTreeDeps = {
    runArgvFn: (file: string, args: string[]) => string;
    logFn: (msg: string) => void;
};

/**
 * Ветка потребителя — `main`, как и везде в ядре (`origin/main` у дерева раннера, #77).
 * Имя не приезжает из конфига намеренно: раннер и так строит все фазы от `origin/main`,
 * и вторая точка настройки завела бы раскладку, где эти два «главных» ref'а расходятся.
 * Дальше по коду это имя используется ДВАЖДЫ и по-разному: как имя локальной ветки, на
 * которой обязано стоять дерево, и как имя ветки на `origin`, которую фетчим. Сливается
 * при этом `FETCH_HEAD` — см. довод у самой команды.
 */
const MAIN = 'main';

/** `git -C <root> …`: свой каталог у каждой команды — `ExecOpts` ядра `cwd` не носит. */
function gitIn(root: string, args: string[]): string[] {
    return ['-C', root, ...args];
}

/**
 * Подтянуть дерево потребителя до `origin/main` после мерджа фазы.
 *
 * Best-effort по определению: следующая фаза строится в дереве РАБОТЫ, и состояние дерева
 * человека её не блокирует. Поэтому здесь нет ни одного пути, который бросает или
 * останавливает петлю, — только исход и строка в логе.
 */
export function updateConsumerTree(
    roots: TResolvedRoots | null,
    { runArgvFn, logFn }: TConsumerTreeDeps,
): TConsumerTreeKind {
    // Раскладки нет — нет и понятия «дерево потребителя»: пути скриптов в этой раскладке
    // относительны дереву работы, и обновлять нечего. Молча: сообщать не о чем.
    if (!roots) return 'no-roots';
    const { consumerRoot, executionRoot } = roots;
    // Дерево потребителя и есть дерево работы: раннер сам держит его на свежем origin/main
    // (detach после мерджа), второе обновление было бы холостым.
    if (consumerRoot === executionRoot) return 'same-tree';

    // Грязь считаем по ОТСЛЕЖИВАЕМЫМ файлам. `runtimeDir` по умолчанию лежит под
    // `consumerRoot` и не версионируется вовсе — с учётом untracked дерево было бы грязным
    // всегда, то есть обновление не случалось бы ни разу в той самой раскладке, ради
    // которой оно написано. Untracked-файл, который слияние затопчет, всё равно не пройдёт:
    // `merge --ff-only` откажется сам и скажет, чем именно.
    let dirty: string;
    try {
        dirty = runArgvFn(
            'git',
            gitIn(consumerRoot, ['status', '--porcelain', '--untracked-files=no']),
        );
    } catch (e) {
        // «Не знаю» — не «чисто»: то же fail-closed, что у `ensureClean` для дерева работы.
        logFn(
            `⚠ Дерево потребителя ${consumerRoot}: git status не отработал (${(e as Error).message}) — ` +
                `не трогаю. Смердженная фаза приедет туда твоим \`git pull --ff-only\`.`,
        );
        return 'failed';
    }
    if (dirty) {
        logFn(
            `⚠ Дерево потребителя ${consumerRoot} грязное — не трогаю: разбирать твои правки ` +
                `раннеру нечем. Смердженная фаза приедет туда после \`git pull --ff-only\`; ` +
                `до этого скрипты потребителя останутся прежней версии.\n${dirty}`,
        );
        return 'dirty';
    }

    // На какой ветке стоит дерево человека. `symbolic-ref` отказом отвечает на detached
    // HEAD — это не сбой, а тот же ответ «не наша ветка», только другим каналом.
    let branch = '';
    try {
        branch = runArgvFn(
            'git',
            gitIn(consumerRoot, ['symbolic-ref', '--quiet', '--short', 'HEAD']),
        ).trim();
    } catch {
        branch = '';
    }
    if (branch !== MAIN) {
        logFn(
            `⚠ Дерево потребителя ${consumerRoot} не на ${MAIN} ` +
                `(${branch || 'detached HEAD'}) — не трогаю: переключать ветку человека раннер ` +
                `не станет. Вернёшься на ${MAIN} — \`git pull --ff-only\` подтянет смердженную фазу.`,
        );
        return 'off-main';
    }

    try {
        // `--no-recurse-submodules` — не гигиена, а исполнение обещания абзацем выше:
        // ДЕФОЛТ `fetch.recurseSubmodules` — `on-demand`, то есть fetch, принёсший новый
        // gitlink продукта, сам зашёл бы в его репозиторий и дописал туда объекты и refs.
        // Ровно в тот каталог, который мы объявили неприкосновенным (ревью, 1-й проход).
        // `-c submodule.recurse=false` закрывает вторую половину: потребитель мог включить
        // рекурсию в своём конфиге, и тогда в подмодуль полез бы ещё и merge.
        runArgvFn(
            'git',
            gitIn(consumerRoot, [
                '-c',
                'submodule.recurse=false',
                'fetch',
                '--no-recurse-submodules',
                'origin',
                MAIN,
            ]),
        );
        // Сливаем ИМЕННО НАФЕТЧЕННОЕ (`FETCH_HEAD`), а не `origin/<MAIN>`: обновление
        // remote-tracking ref'а — побочка `git fetch <remote> <branch>`, и при нестандартном
        // refspec её может не случиться. Тогда слияние с `origin/main` тихо повторило бы
        // ПРОШЛОЕ состояние и отчиталось «обновлено» — худший из исходов: неправда в логе.
        // Только fast-forward: расхождение разбирает человек, а не раннер. Отказ означает,
        // что у него есть свои коммиты в main, и мердж-коммит поверх них был бы произволом.
        runArgvFn(
            'git',
            gitIn(consumerRoot, [
                '-c',
                'submodule.recurse=false',
                'merge',
                '--ff-only',
                'FETCH_HEAD',
            ]),
        );
    } catch (e) {
        logFn(
            `⚠ Дерево потребителя ${consumerRoot} не обновилось (${(e as Error).message}). ` +
                `Разбери руками: \`git -C ${consumerRoot} pull --ff-only\`. До этого скрипты ` +
                `потребителя работают прежней версией.`,
        );
        return 'failed';
    }
    logFn(`✅ Дерево потребителя ${consumerRoot} обновлено до origin/${MAIN} (ff-only).`);
    return 'updated';
}
