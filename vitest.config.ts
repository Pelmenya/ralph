// Конфиг прогона тестов канона. Раньше его не было вовсе: ядро жило каталогом
// `.claude/ralph/` внутри проекта-потребителя, и прогон настраивал ЕГО vitest —
// проект «ralph» со своим include, setupFiles и env. На чистом клоне канона это
// значит «тестов нет», а не «тесты зелёные», поэтому конфиг переезжает сюда.
//
// Два обязательства, без которых прогон меняет смысл:
//
//   1. `RALPH_NO_SIDE_EFFECTS=1` — предохранитель побочек (#138). Боевые дефолты
//      ralph.js/telegram-notifier.ts под ним не исполняют шелл, запись state, npm ci
//      и спавн кодера, а пишут попытку в общий журнал. Без переменной тест, забывший
//      подменить зависимость, ходил бы в реальные git/gh/сеть и был бы «зелёным».
//   2. `setupFiles` — общий afterEach, который сверяет тот журнал. Половина боевых
//      вызовов обёрнута в try/catch, поэтому одного throw для покраснения мало.
//
// Пул форков, а не тредов: тесты правят `process.env` и `process.cwd()`, а часть
// сценариев ловит попытки спавна — общая память тредов делала бы это флаком.
import { defineConfig } from 'vitest/config';

export default defineConfig({
    test: {
        include: ['**/*.test.ts', '**/*.test.mts'],
        exclude: ['node_modules/**', 'tests/__fixtures__/**'],
        setupFiles: ['./tests/test-setup.ts'],
        env: { RALPH_NO_SIDE_EFFECTS: '1' },
        pool: 'forks',
    },
});
