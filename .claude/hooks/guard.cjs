#!/usr/bin/env node
/**
 * PreToolUse hook — жёсткая граница безопасности (детерминированная, не advisory).
 *
 * Блокирует:
 *   - чтение секретов (.env и вариации) через Read и через Bash (cat/type/less...)
 *   - деструктивные команды: рекурсивное удаление, сброс дерева, force-push,
 *     снос базы, сброс миграций
 *   - вызовы MCP вне allowlist
 *   - правку package.json из оболочки (`npm pkg set` и родня): исполняемое обязано
 *     быть видно в диффе
 *   - службы и процессы хоста: systemctl, docker-мутации, kill по чужому pid
 *
 * Это МИНИМАЛЬНЫЙ барьер канона (задача 6): ровно то, без чего петлю нельзя пускать
 * на собственный репозиторий под `bypassPermissions`. Правила о номерах чужого трекера
 * в тексте для площадки сюда не переехали: у канона «чужие» — это потребители, а их
 * имён в публичном дереве быть не может (`tests/project-traces.ts`).
 *
 * **Барьер — часть продукта (#99, Фаза 11).** Исполняемая часть едет с ядром, правила
 * контура — данные потребителя (`.claude/ralph/hooks.json`, разбор — `consumer-data.cjs`).
 * Сессия петли заявлена контрактом запуска `RALPH_CORE_SHA`, и тогда хук сверяет себя с
 * этой ревизией ядра (`core-revision.cjs`): хук из дерева, которое правит PR, не тот,
 * который ревьюили, — несовпадение, недоступность ревизии или ошибка сверки блокируют
 * вызов. Сверка идёт ДО загрузки правил: `require` исполняет их код, и правленые правила,
 * загруженные первыми, подменяли сверщик. Чего самосверка не держит (правку самого
 * сверщика и этого файла), названо в докблоке `core-revision.cjs`.
 *
 * Перед первой сессией раннер проверяет, что барьер вообще держит:
 * `core/guard-probe.ts` подаёт хукам заведомо запрещённые вызовы и не стартует, если
 * хоть один прошёл.
 *
 * Input (stdin): JSON { tool_name, tool_input }
 * Exit 2 + stderr => инструмент блокируется, сообщение уходит агенту.
 * Exit 0 => разрешено.
 *
 * **Отказ самого барьера — тоже блокировка (#172).** Раньше здесь стоял fail-open: любая
 * ошибка кончалась нулём, то есть «разрешено». Пока сессии шли под обычным режимом, это
 * было верно — главное дублировал `permissions.deny`. С переходом раннера на
 * `permissionMode: "bypassPermissions"` дубля не осталось: списки разрешений в том режиме
 * не применяются вовсе (#138), и упавший хук означал открытый канал.
 *
 * Ставка на код выхода — не стилистика, а единственный работающий рычаг. По документации
 * Claude Code (проверено 23.08.2026) у PreToolUse **блокирует только exit 2**: код 1 и
 * код 127 («хук не запустился») считаются ошибкой без блокировки, и вызов исполняется.
 * Поэтому загрузка правил обёрнута в try/catch — иначе `require` бросал бы ДО main() и
 * барьера не было бы ни одного, а процесс падал бы с кодом 1, который ничего не держит.
 *
 * Цена выбора известна и принята: дефект в guard'е останавливает не одну команду, а всю
 * петлю. Условие пересмотра: если ложные блокировки станут регулярными, барьер
 * пересматривается отдельным PR, а не послаблением по ходу работы.
 */

const fs = require('node:fs');

/** Единственный код выхода, который у PreToolUse действительно блокирует вызов. */
const EXIT_BLOCKED = 2;

/**
 * Настоящий выход, сохранённый до того, как код правил получит управление.
 *
 * Правила исполняются в этом же процессе и могут завершить его сами: `process.exit(0)`
 * при загрузке или вместо вердикта — и вызов уходит НЕПРОВЕРЕННЫМ, потому что try/catch
 * такого не ловит (ревью Codex terra, проход 8). Поэтому на время работы правил выход
 * подменяется на исключение, а барьер выходит только этой ссылкой.
 */
const nodeExit = process.exit.bind(process);

/**
 * Отказ с объяснением. Пишет причину агенту и выходит двойкой — из любой точки, включая
 * загрузку модуля правил, то есть ДО того, как появится хоть какое-то мнение о вызове.
 */
function block(reason) {
    process.stderr.write(reason);
    // Обработчики выхода снимаются: `process.on("exit", () => process.reallyExit(0))`
    // в модуле правил переписывал КОД БЛОКИРОВКИ на ноль, то есть отменял отказ уже после
    // решения барьера (ревью Codex terra, проход 9).
    process.removeAllListeners('exit');
    process.removeAllListeners('beforeExit');
    nodeExit(EXIT_BLOCKED);
}

/** Пока правила работают, `process.exit` для них — ошибка, а не выход. */
function withSealedExit(run) {
    process.exit = (code) => {
        throw new Error(`правило вызвало process.exit(${code})`);
    };
    try {
        return run();
    } finally {
        process.exit = nodeExit;
    }
}

/**
 * Описание ошибки, которое само не бросает.
 *
 * Бросить в JavaScript можно что угодно, включая объект без прототипа: у него нет ни
 * `message`, ни `toString`, и `String(error)` падает — прямо в обработчике, то есть вне
 * всякого try. Процесс завершался кодом 1, а он у PreToolUse ничего не блокирует: вызов
 * исполнялся, барьера не было (ревью Codex terra, проход 7).
 */
function describeError(error) {
    try {
        if (error && typeof error.message === 'string') return error.message;
        return String(error);
    } catch {
        return 'ошибка без описания';
    }
}

let decide;
let contour;
let revision = { loop: false, error: null };
let checkCoreRevision;
let isLoopPrompt;
let rulesError = null;
try {
    // Сверщик — первым: он не зависит ни от одного соседа, и до его вердикта ни строчки
    // сверяемого кода не исполняется. Не загрузился — та же неисправность, что правила.
    ({ checkCoreRevision, isLoopPrompt } = withSealedExit(() => require('./core-revision.cjs')));
    try {
        revision = withSealedExit(() => checkCoreRevision());
    } catch (error) {
        revision = { loop: true, error: describeError(error) };
    }
    // Хук не той ревизии не грузит правил вовсе: их код уже не тот, что ревьюили.
    if (!revision.error) {
        decide = withSealedExit(() => require('./guard-rules.cjs').decide);
        if (typeof decide !== 'function') throw new Error('decide не функция');
        // Данные потребителя — в том же try: битые данные — та же неисправность, что не
        // загрузившиеся правила.
        contour = withSealedExit(() => require('./consumer-data.cjs').loadConsumerData());
    }
} catch (error) {
    rulesError = describeError(error);
}

/**
 * ПУТИ ВОССТАНОВЛЕНИЯ ИЗНУТРИ СЕССИИ ЗДЕСЬ НЕТ, и это осознанно.
 *
 * Неисправный барьер блокирует всё, включая `Edit` и `Write`, которыми его чинят: сессия
 * не может восстановить себя, нужен человек. Поймано живьём дважды 23.08.2026.
 *
 * Аварийный люк для этого случая был написан здесь же и вынесен из PR обратно: за пять
 * кругов ревью он дал ТРИНАДЦАТЬ дефектов, пять из которых открывали канал наружу —
 * чтение секретов рядом с хуками, правку соседних lifecycle-хуков (то есть исполнение
 * кода при следующем старте сессии), проход по символической и жёсткой ссылке, обход через
 * `process.exit` из правил. Механизм, который сам открывает то, что закрывает барьер,
 * ставить прицепом к чужой задаче нельзя — правило репозитория говорит ровно это:
 * ослабление барьера едет ОТДЕЛЬНЫМ PR.
 *
 * Задача заведена отдельно (#175); до неё восстановление барьера — работа человека.
 */

function readStdin() {
    return new Promise((resolve) => {
        let data = '';
        process.stdin.setEncoding('utf-8');
        process.stdin.on('data', (c) => (data += c));
        process.stdin.on('end', () => resolve(data));
        process.stdin.on('error', () => resolve(''));
        setTimeout(() => resolve(data), 5000);
    });
}

/**
 * Переходный признак петли по транскрипту (`core-revision.cjs`): раннер контракт сессиям
 * пока не передаёт, и забор данных контура по одному `revision.loop` не действовал бы ни
 * в одной настоящей сессии петли (ревью Фазы 11). Транскрипт читается лениво — только
 * когда вызов трогает данные. Назван, но не читается — считаем петлёй: заблокирована
 * будет одна правка данных, а пропуск открыл бы канал.
 */
function loopByTranscript(transcriptPath) {
    if (typeof transcriptPath !== 'string' || transcriptPath === '') return false;
    let lines;
    try {
        lines = fs.readFileSync(transcriptPath, 'utf-8').split('\n');
    } catch {
        return true;
    }
    return isLoopPrompt(lines);
}

async function main() {
    const raw = await readStdin();
    // Пустой вход и битый JSON — это не «нет мнения о вызове», а «вход не тот, что обещан
    // контрактом хука». Пропускать по такому признаку значит открывать канал каждому, кто
    // сумеет сломать вход.
    if (!raw.trim()) {
        block(
            '[guard.cjs] Пустой вход: PreToolUse обязан подать JSON на stdin. ' +
                'Вызов заблокирован — судить о нём не по чему.',
        );
    }

    let input;
    try {
        input = JSON.parse(raw);
    } catch (error) {
        block(
            `[guard.cjs] Вход не разобрался как JSON (${error.message}). ` +
                'Вызов заблокирован — судить о нём не по чему.',
        );
    }

    if (!input || typeof input !== 'object' || Array.isArray(input)) {
        block(
            '[guard.cjs] Вход разобрался, но это не объект вызова. ' +
                'Вызов заблокирован — судить о нём не по чему.',
        );
    }

    const toolName = input.tool_name || '';
    const toolInput = input.tool_input || {};

    if (rulesError) {
        block(
            `[guard.cjs] Правила барьера не загрузились: ${rulesError}. Вызов заблокирован — ` +
                'проверять его нечем. Барьер чинит человек: сессия этого сделать не может.',
        );
    }

    if (revision.error) {
        block(
            `[guard.cjs] Ревизия хука не сверилась с ядром: ${revision.error} Вызов ` +
                'заблокирован: хук не той ревизии — не тот барьер, который ревьюили.',
        );
    }

    let verdict;
    try {
        verdict = withSealedExit(() =>
            decide(toolName, toolInput, {
                contour,
                loop: revision.loop || (() => loopByTranscript(input.transcript_path)),
            }),
        );
        // Вердикт не того вида — та же неисправность, что исключение: барьер ничего не
        // сказал о вызове. Без этой проверки `decide: () => ({})` пропускал всё (поле
        // `blocked` равно undefined), а `() => undefined` бросал НИЖЕ, вне try, и снова
        // запирал сессию без люка (ревью, проход 6).
        if (!verdict || typeof verdict.blocked !== 'boolean') {
            throw new Error(`вердикт не того вида: ${JSON.stringify(verdict)}`);
        }
    } catch (error) {
        // Ошибка ИСПОЛНЕНИЯ правила — та же неисправность, что и ошибка загрузки: барьер о
        // вызове ничего не знает, значит вызов не проходит.
        block(
            `[guard.cjs] Правило барьера неисправно: ${describeError(error)}. Вызов ` +
                'заблокирован fail-closed. Почини правило — обойти барьер нельзя.',
        );
    }
    if (verdict.blocked) block(verdict.reason);
}

main().then(
    // Выход явный, а не «когда опустеет очередь»: таймер чтения stdin держит event loop
    // ещё пять секунд после вердикта, и без этой строки каждый разрешённый вызов ждал бы
    // их впустую — барьер стоит на КАЖДОМ вызове инструмента.
    () => nodeExit(0),
    (error) =>
        // Дефект внутри правил (брошенное исключение, опечатка в регэкспе) означает, что
        // барьер о вызове ничего не знает. Прежний `.catch(() => undefined)` в этом месте
        // отдавал ноль, то есть разрешал вызов ровно тогда, когда проверка не сработала.
        block(
            `[guard.cjs] Ошибка барьера при разборе вызова: ${describeError(error)}. ` +
                'Вызов заблокирован fail-closed. Почини правило — обойти барьер нельзя.',
        ),
);
