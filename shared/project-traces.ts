/**
 * Скан проектных следов: чего публичный канон не имеет права нести.
 *
 * Зачем. Ядро живёт в ПУБЛИЧНОМ репозитории и подключается потребителями как подмодуль.
 * Утечка сюда необратима: git-история остаётся публичной и после правки, а следы копятся
 * не по злому умыслу, а сами — комментарием об истории решения, дефолтом в скрипте
 * провижна, путём машины в фикстуре теста. Дисциплина такое не ловит: следы считаются
 * сотнями, и каждый по отдельности выглядит безобидно.
 *
 * Домены потребителей сторожит тот же словарь, а не структурный класс, и это решение,
 * а не пробел: канон законно ссылается на доку площадок и вендоров, поэтому «любой домен,
 * кроме example.com» краснел бы на каждой второй ссылке в доке. Барьер, тонущий в ложных
 * срабатываниях, отключают — и тогда он не сторожит уже ничего.
 *
 * ПОЧЕМУ ИМЁН ПОТРЕБИТЕЛЕЙ НЕТ В ЭТОМ ФАЙЛЕ. Соблазн велик: списком «эти имена не едут в
 * канон» чек стал бы точным. Но такой список — сам след, причём вечный: он назвал бы
 * приватные репозитории прямо в публичной истории продукта. Поэтому имена приходят
 * СНАРУЖИ, через `RALPH_TRACE_DENY` (см. denyNamePattern), а в дереве остаются только
 * СТРУКТУРНЫЕ классы — те, что распознаются по форме, а не по словарю.
 *
 * Два вердикта (#117). Значение в логике — блокер. Пример в комментарии, доке или
 * фикстуре — допустим, но только АБСТРАКТНЫЙ; конкретный тоже красный. Граница проходит
 * не по «код или комментарий», а по форме самого значения: абстрактные формы ниже не
 * матчатся ни одним классом вовсе, поэтому пример с ними зелёный везде.
 *
 * Санкционированные абстрактные формы:
 *   пути      — `/path/to/app`, `/path/to/app-ralph`, `/home/user/…`
 *   проекты   — `your-project`, `your-org`, `app`
 *   домены    — `example.com` и поддомены (RFC 2606: домен, зарезервированный под примеры)
 *
 * TS-модуль без билд-шага: исполняется нативным type stripping Node 24.
 */

/** Один класс следа: как называется, что ищет, чем заменяется. */
export type TTraceClass = {
    /** Короткое имя для сообщения об отказе. */
    name: string;
    /** Что именно запрещено — попадает в текст отказа как объяснение. */
    what: string;
    /** Чем это пишется в каноне. */
    instead: string;
    re: RegExp;
};

/** Коммит, чьё сообщение уже несёт след и исправлено быть не может. */
export type THistoryExemption = {
    /** Полный SHA: короткий однажды совпадёт с префиксом чужого коммита. */
    sha: string;
    /** Почему след не убран — попадает в отказ, если запись протухнет. */
    reason: string;
};

/**
 * Исключения скана сообщений — поимённо и только по полному SHA.
 *
 * След в сообщении коммита `main` не чинится ничем: защита ветки отвергает и прямой push,
 * и переписывание истории (`prevent_non_pr_changes`). Без записи здесь скан со словарём
 * краснел бы навсегда — на каждом гейте, в том числе у петли, которая тогда не смерджит
 * ничего. Исключение — не послабление барьера: оно гасит ровно одно известное сообщение,
 * а тест рядом краснеет, если коммита в истории нет или скан на нём больше ничего не
 * находит. Имя, которое здесь прощено, в эту запись не пишется: запись — тоже дерево.
 */
export const HISTORY_EXEMPT: readonly THistoryExemption[] = [
    {
        sha: '9f4c1fbc6f2df9d064975fb1edccaa186ef54f35',
        reason:
            'сообщение от 25.08.2026 называет потребителя; найдено после словаря скана, ' +
            'история `main` защищена от переписывания, исключение — решение человека 26.10',
    },
];

export const TRACE_CLASSES: readonly TTraceClass[] = [
    {
        name: 'machine-path',
        what: 'абсолютный путь домашнего каталога конкретной машины',
        instead: '`/path/to/app` (или `/home/user/…`, если важно, что это домашний каталог)',
        // Корневой домашний каталог — всегда машина: абстрактной формы у него нет, для
        // примера есть `/path/to/…`. `/home/<кто-то>/` — тоже машина, КРОМЕ `/home/user/`: это
        // общепринятая безличная форма, ею и пишутся примеры.
        re: /\/root\/|\/home\/(?!user\/)[\w.-]+\//,
    },
    {
        name: 'ssh-host',
        what: 'адрес конкретного хоста в команде (ssh/scp/rsync)',
        instead: 'плейсхолдер `user@host` либо переменная окружения',
        re: /\b(?:ssh|scp|rsync)\s+[^\s]*\b[\w.-]+@(?!host\b)[\w.-]+\.[a-z]{2,}/i,
    },
];

/**
 * Имена потребителей — из окружения, а не из дерева (см. докблок).
 *
 * `RALPH_TRACE_DENY` — список через запятую: имена репозиториев, организаций, доменов,
 * а также проектных МЕТОК и ФАЗ. Последние два попадают сюда не по недосмотру: у них нет
 * структурной формы вовсе (`area:acme` и «Витрина · Фаза 2» неотличимы от обычного
 * текста), поэтому словарь — единственный способ их распознать.
 *
 * Не задан — структурные классы всё равно работают; это НЕ повод считать скан пройденным
 * молча, поэтому вызывающий тест сообщает, что словарь пуст.
 */
export function denyNamePattern(env: NodeJS.ProcessEnv = process.env): RegExp | null {
    const raw = (env.RALPH_TRACE_DENY ?? '').trim();
    if (raw === '') return null;
    const names = raw
        .split(',')
        .map((s) => s.trim())
        .filter((s) => s !== '')
        // Экранируем: имена приходят от человека, а не из кода, и точка в домене не
        // обязана значить «любой символ».
        .map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
    if (names.length === 0) return null;
    // Границами слова совпадение НЕ обрамляем, и это решение, а не упущение (ревью !17):
    // `acme-shop` обязан краснеть и внутри `acme-shop-api`, и в `git@host:acme-shop.git`,
    // и в середине URL — след остаётся следом в любом окружении символов. Плата —
    // возможное ложное срабатывание на имени, случайно вложенном в чужое слово; в барьере
    // публичности она правильной стороной: лишний красный чинится за минуту, утечка в
    // публичную историю не чинится вовсе.
    return new RegExp(names.join('|'), 'i');
}

export type TTraceFinding = {
    /** Номер строки, 1-based. */
    line: number;
    /** Имя класса либо 'deny-name' для словарного совпадения. */
    cls: string;
    /** Сама строка, обрезанная — в отказ уходит она, а не весь файл. */
    excerpt: string;
};

/**
 * Находки по одному тексту. Сканируется ВЕСЬ текст, включая комментарии: абстрактные
 * формы не матчатся, поэтому пример в комментарии проходит и без разбора «код это или
 * не код» (тот разбор нужен соседнему скану чистоты ядра, где запрещены значения
 * проекта, а поясняющий пример разрешён).
 */
export function traceFindings(
    text: string,
    opts: { deny?: RegExp | null; classes?: readonly TTraceClass[] } = {},
): TTraceFinding[] {
    const classes = opts.classes ?? TRACE_CLASSES;
    const deny = opts.deny ?? null;
    const out: TTraceFinding[] = [];
    text.split('\n').forEach((line, i) => {
        for (const cls of classes) {
            if (cls.re.test(line)) out.push({ line: i + 1, cls: cls.name, excerpt: line.trim() });
        }
        if (deny?.test(line)) out.push({ line: i + 1, cls: 'deny-name', excerpt: line.trim() });
    });
    return out;
}

/** Текст отказа: что нашли, где и чем это писать вместо. */
export function explain(rel: string, findings: readonly TTraceFinding[]): string {
    const byClass = new Map(TRACE_CLASSES.map((c) => [c.name, c]));
    return findings
        .map((f) => {
            const cls = byClass.get(f.cls);
            const tail = cls
                ? `${cls.what}; в каноне это ${cls.instead}`
                : 'имя из RALPH_TRACE_DENY';
            return `${rel}:${String(f.line)} — ${tail}\n    ${f.excerpt.slice(0, 120)}`;
        })
        .join('\n');
}
