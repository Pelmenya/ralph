/**
 * Интерфейс пакета харнесса — то, что реестр берёт из `harnesses/<имя>/package.ts` (Фаза 16c,
 * #180).
 *
 * Отдельным модулем, а не в реестре, по одной причине: реестр грузит пакеты `await import()`
 * на верхнем уровне, и пакет, импортирующий реестр ради типа или константы, замкнул бы цикл
 * модулей на незавершённом `await` — загрузка встала бы навсегда. Здесь нет ни загрузки, ни
 * побочек, и пакет вправе его импортировать.
 *
 * Версия интерфейса — отдельно от версии схемы описания (`harnesses/descriptor.ts`): схема
 * говорит о данных пакета, интерфейс — о его коде. Пакет объявляет ту версию, под которую
 * написан, ЛИТЕРАЛОМ, а не этой константой: импортированная константа совпадала бы с
 * реестром всегда, и сверка ничего бы не ловила.
 *
 * TS-модуль без билд-шага (erasable-only), без побочек.
 */
import type { GuardHook, HarnessProbe } from './harness-guard.ts';

export const HARNESS_INTERFACE_VERSION = 1;

/**
 * Хук барьера так, как его позовёт CLI: matcher в семантике этого CLI, команда, таймаут и
 * почему он НЕ вправе считаться блокирующим (`null` — вправе). Такой хук проба всё равно
 * запускает: безобидное он обязан пропустить, как и все.
 */
export type RegisteredGuardHook = {
    matcher: unknown;
    command: string;
    timeoutSec: number;
    cannotBlock: string | null;
};

/**
 * Регистрация барьера, прочитанная обратно из того, что уйдёт в CLI. `problems` — причины,
 * по которым регистрация не годится целиком (CLI не запустит ни одного хука), — проба их
 * называет и хуков не запускает.
 */
export type GuardRegistration = { hooks: RegisteredGuardHook[]; problems: string[] };

/**
 * Регистрация, которую CLI исполняет плагином, а не командой хука (OpenCode, #213): CLI грузит
 * исходник и зовёт его обработчик, а хуки барьера зовёт уже сам плагин. Проба поэтому
 * исполняет плагин на событии CLI, а не хуки в обход него: разбор события — часть плагина, и
 * проба мимо него увидела бы барьер, которого у сессии нет.
 */
export type GuardPlugin = {
    /** Исходник плагина из хуков барьера в общей форме — ровно то, что ляжет в каталог CLI. */
    source(guardHooks: readonly GuardHook[]): string;
    /** Хуки, зашитые в исходник, прочитанные обратно; причины — плагин не зовёт барьер. */
    read(source: string): GuardRegistration;
    /** Аргументы обработчика плагина на вызове пробы — в форме, в какой их подаёт CLI. */
    event(probe: HarnessProbe): {
        input: Record<string, unknown>;
        output: Record<string, unknown>;
    };
};

export type HarnessPackage = {
    interfaceVersion: number;
    harness: string;
    /**
     * Регистрация барьера так, как она уйдёт в CLI, прочитанная обратно. Источника два, и
     * пакет берёт свой: `settings` — настройки сессии, которые собирает раннер (их читает
     * харнесс, в чьём формате они собраны); `guardHooks` — хуки барьера из тех же настроек
     * в общей форме (`guardHooksOf` ядра), из них регистрацию строят харнессы, которые
     * настроек сессии не читают (#181). Хуков не передали — регистрации из них нет: проба
     * такого пакета красная, а не зелёная по пустому списку.
     */
    guardRegistration(settings: unknown, guardHooks?: readonly GuardHook[]): GuardRegistration;
    /** Состав отрицательной и безобидной пробы в терминах CLI. */
    probes: readonly HarnessProbe[];
    /** Накрывает ли matcher инструмент — по правилам этого CLI. */
    matcherCovers(matcher: unknown, toolName: string): boolean;
    /** Вход хука в форме, в какой его подаёт CLI. */
    hookPayload(probe: HarnessProbe, projectDir: string): string;
    /** Кладёт ли CLI `CLAUDE_PROJECT_DIR` в окружение хука сам. */
    setsProjectDirEnv: boolean;
    /** Исполним ли в сессии барьер скиллов: CLI отдаёт хуку транскрипт с вызовом `Skill`. */
    skillBarrier: boolean;
    /**
     * Что барьер у этого CLI НЕ держит — строка `⚠` старта рядом с «проба пройдена»; `null` —
     * предела, который проба не видит, нет. Поле обязательное: пакет, промолчавший о пределе,
     * выглядел бы харнессом без него.
     */
    guardLimit: string | null;
    /**
     * Регистрация плагином (`GuardPlugin`); `null` — хуки командой, их исполняет проба сама.
     * Поле обязательное: выбор способа пробы — признак пакета, а не имя харнесса в ядре.
     */
    plugin: GuardPlugin | null;
};
